#  Typecasting = The process of converting one data type into another data type
#             str() = converts a value to a string
#             int() = converts a value to an integer
#             float() = converts a value to a float
#             bool() = converts a value to a boolean


name = "Asadullah Al Jubaer"
age = 20
height = 5.5
gpa = 3.2
is_student = True


print(type(name))
print(type(age))
print(type(height))
print(type(gpa))
print(type(is_student))
print()

gpa = int(gpa)
print(gpa)
print(type(gpa))
print()

age = float(age)
print(age)
print(type(age))
